"""Within-group label-permutation test for the small-capacity supplement.

GroupKFold with 4 groups is leave-one-tensor-out (the most defensible split).
The null is generated by permuting clean/embedded labels within each group,
which preserves block-level distributions and the group structure. Reported
p-value = fraction of permutations with AUC >= observed.
"""
import json
import numpy as np
from pathlib import Path
from sklearn.linear_model import LogisticRegression
from sklearn.preprocessing import StandardScaler
from sklearn.model_selection import GroupKFold
from sklearn.metrics import roc_auc_score

BASE = Path("/workspace/nes_run_20261016_anchor_ablation")
d = np.load(BASE / "out/detectability_smallcap_v1/features.npz", allow_pickle=True)
X = d["X"]
meta = [json.loads(s) for s in d["meta_json"]]
y = np.array([1 if m["label"] == "embedded" else 0 for m in meta])
g = np.array([f"{m['model']}::{m['tensor']}" for m in meta])

N_PERM = 200
SEED = 20261016


def loto_auc(Xa, ya, ga):
    gkf = GroupKFold(n_splits=len(set(ga)))
    oof = np.zeros(len(ya))
    for tr, te in gkf.split(Xa, ya, ga):
        sc = StandardScaler().fit(Xa[tr])
        clf = LogisticRegression(max_iter=2000, random_state=SEED, class_weight="balanced")
        clf.fit(sc.transform(Xa[tr]), ya[tr])
        oof[te] = clf.predict_proba(sc.transform(Xa[te]))[:, 1]
    return float(roc_auc_score(ya, oof)), oof


obs_auc, _ = loto_auc(X, y, g)
rng = np.random.default_rng(SEED)
null = []
group_idx = {gg: np.where(g == gg)[0] for gg in sorted(set(g))}
for _ in range(N_PERM):
    yp = y.copy()
    for gg, idx in group_idx.items():
        yp[idx] = rng.permutation(y[idx])
    try:
        a, _ = loto_auc(X, yp, g)
        null.append(a)
    except ValueError:
        continue
null = np.array(null)
p = float((np.sum(null >= obs_auc) + 1) / (len(null) + 1))

res = {
    "detector": "logistic_regression",
    "split": "leave-one-tensor-out (GroupKFold, 4 groups)",
    "observed_auc": obs_auc,
    "null_mean": float(null.mean()), "null_std": float(null.std()),
    "null_p95": float(np.percentile(null, 95)),
    "n_permutations": int(len(null)),
    "p_value": p,
    "note": "null permutes clean/embedded labels within each group; exploratory given 4 groups",
}
json.dump(res, open(BASE / "out/detectability_smallcap_v1/permutation_test.json", "w"), indent=2)
print(json.dumps(res))
